import kotlinx.serialization.Serializable

/** Sonarr ReleaseResource wire contract. Dates remain unparsed strings. */
@Serializable
data class ReleaseResource(
    val id: Int = 0,
    val guid: String? = null,
    val quality: QualityModel = QualityModel(),
    val qualityWeight: Int = 0,
    val age: Int = 0,
    val ageHours: Double = 0.0,
    val ageMinutes: Double = 0.0,
    val size: Long = 0L,
    val indexerId: Int = 0,
    val indexer: String? = null,
    val releaseGroup: String? = null,
    val subGroup: String? = null,
    val releaseHash: String? = null,
    val title: String? = null,
    val fullSeason: Boolean = false,
    val sceneSource: Boolean = false,
    val seasonNumber: Int = 0,
    val seasonNumbers: List<Int>? = null,
    val languages: List<Language>? = null,
    val languageWeight: Int = 0,
    val airDate: String? = null,
    val seriesTitle: String? = null,
    val episodeNumbers: List<Int>? = null,
    val absoluteEpisodeNumbers: List<Int>? = null,
    val mappedSeasonNumber: Int? = null,
    val mappedEpisodeNumbers: List<Int>? = null,
    val mappedAbsoluteEpisodeNumbers: List<Int>? = null,
    val mappedSeriesId: Int? = null,
    val mappedEpisodeInfo: List<ReleaseEpisodeResource>? = null,
    val approved: Boolean = false,
    val temporarilyRejected: Boolean = false,
    val rejected: Boolean = false,
    val tvdbId: Int = 0,
    val tvRageId: Int = 0,
    val imdbId: String? = null,
    val rejections: List<String>? = null,
    val publishDate: String = "1970-01-01T00:00:00Z",
    val commentUrl: String? = null,
    val downloadUrl: String? = null,
    val infoUrl: String? = null,
    val episodeRequested: Boolean = false,
    val downloadAllowed: Boolean = false,
    val releaseWeight: Int = 0,
    val customFormats: List<CustomFormatResource>? = null,
    val customFormatScore: Int = 0,
    val sceneMapping: AlternateTitleResource = AlternateTitleResource(),
    val magnetUrl: String? = null,
    val infoHash: String? = null,
    val seeders: Int? = null,
    val leechers: Int? = null,
    val protocol: DownloadProtocol = DownloadProtocol.UNKNOWN,
    val indexerFlags: Int = 0,
    val isDaily: Boolean = false,
    val isAbsoluteNumbering: Boolean = false,
    val isPossibleSpecialEpisode: Boolean = false,
    val special: Boolean = false,
    val seriesId: Int? = null,
    val episodeId: Int? = null,
    val episodeIds: List<Int>? = null,
    val downloadClientId: Int? = null,
    val downloadClient: String? = null,
    val shouldOverride: Boolean? = null
)
